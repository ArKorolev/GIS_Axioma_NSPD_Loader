# -*- coding: utf-8 -*-
"""НСПД Loader — плагин загрузки кадастровых данных с НСПД ФГИС ЕГРН (Росреестр).

Назначение файла:
    Точка входа плагина ГИС «Панорама/Аксиома 7.1». Пакет как целое
    регистрируется в Аксиоме через класс NspdLoaderPlugin (наследник
    axipy.Plugin): он создаёт команду «Данные НСПД» на панели и по клику
    запускает интерфейс модуля (main.run).

Состав пакета (что за что отвечает):
    __init__.py         — этот файл: регистрация плагина и команды вызова;
    main.py             — открытие/закрытие док-окна с виджетом модуля;
    widget.py           — UI: ввод номеров, лог, прогресс, поток Worker;
    nspd_processor.py   — оркестрация: цикл запросов, повторы, сводка;
    nspd_client.py      — клиент поиска объектов на портале НСПД;
    categories.py       — категории объектов НСПД (колонки, ЕЗП, статусы);
    nspd_geometry.py    — общая обработка геометрии (полигоны/точки/линии);
    nspd_table.py       — временные таблицы axipy, слои карты, семантика;
    nspd_transport.py   — HTTP-транспорт (SSL, задержки, лимит запросов);
    nspd_utils.py       — безопасные преобразования значений из НСПД;
    manifest.ini        — манифест плагина Аксиомы (имя, версия, точка входа).

Правила работы с геометрией НСПД (реализованы в nspd_geometry.py):
    - загружаемой геометрией объекта являются ТОЛЬКО Polygon/MultiPolygon
      (многоконтурный участок либо полигон с дырами);
    - LineString/MultiLineString — осевые линии, не грузятся;
    - Point/MultiPoint — адресные привязки, грузятся только когда
      собственная граница (полигон) объекта отсутствует.
"""

import logging

from axipy import Plugin, Position, ActionManager

logger = logging.getLogger("NSPD_Loader")


class NspdLoaderPlugin(Plugin):
    """Класс плагина. Создаётся ядром Аксиомы при загрузке пакета.

    Отвечает за:
    - регистрацию команды «Данные НСПД» в меню/панели («Основные» → «Команды»);
    - запуск интерфейса модуля по клику (отложенный импорт main.run —
      чтобы тяжёлые Qt-модули не импортировались при старте ГИС);
    - корректную выгрузку: остановка потока, удаление команды (unload).
    """

    def __init__(self):
        # Иконка команды: стандартная иконка WMS-слоя, если доступна
        try:
            icon = ActionManager.icon_by_name("layer_wms")
        except Exception:
            icon = None

        # Команда вызова модуля, создаётся средствами базового класса Plugin
        self._action = self.create_action(
            title="Данные НСПД",
            icon=icon,
            on_click=self._on_click,
        )
        # Размещение команды на панели инструментов
        Position("Основные", "Команды").add(self._action)

    def _on_click(self):
        """Обработчик клика по команде: открывает/показывает окно модуля."""
        from .main import run
        run()

    def unload(self):
        """Выгрузка плагина: останавливает загрузку и снимает команду."""
        from .main import stop
        stop()
        try:
            self._action.remove()
        except Exception as e:
            logger.error("Ошибка при выгрузке: %s", e)